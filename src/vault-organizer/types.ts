/**
 * Options for generating organization suggestions
 */
export interface SuggestionOptions {
  /** Minimum confidence threshold (0-1) */
  readonly minConfidence?: number;
  /** Maximum number of suggestions to generate */
  readonly maxSuggestions?: number;
  /** Target folder structure (preferred categories) */
  readonly targetStructure?: readonly string[];
  /** Whether to suggest renames for unclear filenames */
  readonly suggestRenames?: boolean;
  /** Whether to consolidate related files */
  readonly consolidateRelated?: boolean;
}

/**
 * Options for executing reorganization
 */
export interface ExecutionOptions {
  /** Perform dry run without making changes */
  readonly dryRun?: boolean;
  /** Create backup before executing */
  readonly createBackup?: boolean;
  /** Backup location path */
  readonly backupPath?: string;
  /** Update links in other files */
  readonly updateLinks?: boolean;
  /** Stop on first error */
  readonly stopOnError?: boolean;
  /** Skip operations below confidence threshold */
  readonly skipLowConfidence?: boolean;
  /** Minimum confidence to execute (0-1) */
  readonly minExecutionConfidence?: number;
}

// ============================================
// Custom Error Classes
// ============================================

/**
 * Error during vault analysis
 *
 * Thrown when analyzing vault structure or content fails.
 */
export class VaultAnalysisError extends Error {
  constructor(
    message: string,
    public readonly path?: string,
    public readonly cause?: unknown
  ) {
    super(message);
    this.name = 'VaultAnalysisError';
    Object.setPrototypeOf(this, VaultAnalysisError.prototype);
  }
}

/**
 * Error during vault reorganization
 *
 * Thrown when executing reorganization operations fails.
 */
export class VaultReorganizationError extends Error {
  constructor(
    message: string,
    public readonly operation?: ReorganizationOperation,
    public readonly rollbackAvailable?: boolean,
    public readonly cause?: unknown
  ) {
    super(message);
    this.name = 'VaultReorganizationError';
    Object.setPrototypeOf(this, VaultReorganizationError.prototype);
  }
}

/**
 * Error when rollback operation fails
 *
 * Critical error that indicates data may be in inconsistent state.
 */
export class RollbackError extends Error {
  constructor(
    message: string,
    public readonly failedOperations: readonly ReorganizationOperation[],
    public readonly cause?: unknown
  ) {
    super(message);
    this.name = 'RollbackError';
    Object.setPrototypeOf(this, RollbackError.prototype);
  }
}

