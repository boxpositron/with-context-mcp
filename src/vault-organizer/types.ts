/**
 * Filter criteria for vault files
 */
export interface FileFilter {
  /** Filter by file extension */
  readonly extensions?: readonly string[];
  /** Filter by minimum file size */
  readonly minSize?: number;
  /** Filter by maximum file size */
  readonly maxSize?: number;
  /** Filter by date range */
  readonly dateRange?: {
    readonly from?: string; // ISO 8601
    readonly to?: string; // ISO 8601
  };
  /** Filter by folder path */
  readonly folders?: readonly string[];
  /** Filter by tags */
  readonly tags?: readonly string[];
  /** Filter by orphan status */
  readonly orphansOnly?: boolean;
}

/**
 * Sort criteria for vault files
 */
export type SortCriteria =
  | 'name'
  | 'size'
  | 'created'
  | 'modified'
  | 'path'
  | 'wordCount'
  | 'linkCount';

/**
 * Sort options
 */
export interface SortOptions {
  /** Sort by criteria */
  readonly by: SortCriteria;
  /** Sort direction */
  readonly direction: 'asc' | 'desc';
}

/**
 * Pagination options for large result sets
 */
export interface PaginationOptions {
  /** Page number (0-based) */
  readonly page: number;
  /** Items per page */
  readonly pageSize: number;
}

/**
 * Paginated result wrapper
 */
export interface PaginatedResult<T> {
  /** Items in current page */
  readonly items: readonly T[];
  /** Current page number (0-based) */
  readonly page: number;
  /** Items per page */
  readonly pageSize: number;
  /** Total number of items */
  readonly total: number;
  /** Total number of pages */
  readonly totalPages: number;
  /** Whether there's a next page */
  readonly hasNext: boolean;
  /** Whether there's a previous page */
  readonly hasPrevious: boolean;
}
